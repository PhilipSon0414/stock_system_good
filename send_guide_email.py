#!/usr/bin/env python3
"""
스캔 리포트 읽는 법 + 투자 전략 가이드 이메일 발송
daily_scan.py 스캔 완료 후 자동 호출 (또는 단독 실행)
"""
from email_sender import send_report
from datetime import datetime


def build_guide() -> str:
    now = datetime.now().strftime('%Y년 %m월 %d일')
    sep  = '═' * 62
    sep2 = '─' * 62

    lines = []
    lines.append(sep)
    lines.append(f'  국내 주식 스캔 리포트 읽는 법 + 투자 전략 가이드')
    lines.append(f'  {now}  |  세력 분석 시스템 v2.0')
    lines.append(sep)

    # ── 1. 리포트 구조 ──────────────────────────────────────────────────
    lines.append('''
━━ 1. 리포트 구조 한눈에 보기 ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

① 의사결정 핵심 원칙 박스
   ─ 데이터 검증 결과로 도출된 핵심 가이드라인
   ─ 세력점수와 ML 티어가 실제 예측력을 가짐
   ─ 합산점수 단독으로는 예측력 낮음 (참고용)

② 매크로 컨텍스트
   ─ 코스피/코스닥 5일/20일 추세
   ─ VIX(공포지수), 원달러 환율
   ─ 매크로 점수: +이면 시장 우호, -이면 리스크 주의

③ ★★★★ 엘리트픽
   ─ 세력·수급·거래량 조건 동시 충족 종목
   ─ 4가지 Tier 조건 중 하나 이상 해당

④ ★★★ 거래량 기반 즉시 진입 후보
   ─ 폭발형(거래량 2x+): 세력이 이미 진입 시작
   ─ 잠복형(거래량 0.3x 미만): 조용히 매집 중

⑤ ★★ 급등 임박 후보 (재발화)
   ─ 과거 이력 3회+ 후 재출현 = 반복 패턴 종목

⑥ 전체 순위표
   ─ 세력점수 기준 정렬 (합산점수 아님)
   ─ 스테이지 컬럼: 🔥D-1 ⚡D-2 📈D-3 등

⑦ 상세 분석 (상위 20종목)
   ─ OB(오더블록) 매매전략 포함
   ─ 진입가/목표가/손절가/R:R 비율''')

    lines.append(sep2)

    # ── 2. 점수 체계 ──────────────────────────────────────────────────
    lines.append('''
━━ 2. 점수 체계 완전 해설 ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

┌─ 세력점수 (0~100점) ─────────────────────────────────────────┐
│  40점 이하  : 세력 흔적 미약 — 관망                           │
│  41~59점   : 세력 주시 중 — 모니터링                          │
│  60~74점   : 세력 활성화 — 진입 검토                          │
│  75~89점   : 세력 강세 — 적극 검토                            │
│  90점↑     : 세력 집중 — 즉시 진입 검토                       │
└──────────────────────────────────────────────────────────────┘

┌─ ML 티어 (데이터 검증) ──────────────────────────────────────┐
│  Tier-S : 세력≥80 + MA20위 → 예상적중 35% (기준 17%의 2.1배)  │
│  Tier-A : 세력≥70 + 거래량≥2x → 예상적중 28%                 │
│  Tier-B : 세력≥60 + 재발화 → 예상적중 22%                    │
│  Tier-C : 기본 조건 충족 → 예상적중 17% (시장 평균)           │
│  Tier-D : 조건 미달 — 보류                                    │
└──────────────────────────────────────────────────────────────┘

┌─ 급등 스테이지 (ML 모델 예측) ──────────────────────────────┐
│  🔥 D-1 : 내일 급등 가능성 가장 높음 — 오늘 매수 검토         │
│  ⚡ D-2 : 2일 후 급등 후보 — 분할 매수 시작                   │
│  📈 D-3 : 3일 후 후보 — 조기 포착 / 관심 등록                │
│  👀 D-4 : 4일 후 — 워치리스트 추가                            │
│  💤 D-5 : 5일 후 — 조용한 매집 단계                          │
│  🚀 D+0 : 오늘 급등 발생 — 신규 진입 금지 (이미 발동)        │
│  📉 D+1 : 어제 급등 후 반응 — 단기 차익 / 후속 대응          │
│                                                                │
│  ※ 모델 정밀도: D-1 기준 약 12% (랜덤 6%의 2배 lift)         │
│     세력점수 ≥70 AND 스테이지 D-1/D-2 조합 시 신뢰도 ↑       │
└──────────────────────────────────────────────────────────────┘''')

    lines.append(sep2)

    # ── 3. OB 매매전략 읽는 법 ────────────────────────────────────────
    lines.append('''
━━ 3. OB(오더블록) 매매전략 읽는 법 ━━━━━━━━━━━━━━━━━━━━━━━━━━

오더블록 = 세력이 대량 매수한 가격대 (지지/저항 구간)

예시 리포트:
  ┌─ OB 기반 매매 전략 ──────────────────────────────────
  │  진입가: 45,200원  ← 강세OB 눌림목 대기
  │  목표가: 52,300원  (+15.7%) ← 약세OB 저항 직전
  │  손절가: 43,800원  (-3.1%)  ← 강세OB 하단 하회 시
  │  R:R = 4.8:1  ✅ 유리
  └──────────────────────────────────────────────────────

해석:
  ■ 진입가  : 오더블록 상단 또는 현재가. 지정가 주문 활용
  ■ 목표가  : 다음 저항 구간. 분할 매도 권장 (50%+50%)
  ■ 손절가  : 오더블록 하단 이탈 시 즉시 손절 (기계적 실행)
  ■ R:R 비율: 목표수익 ÷ 리스크
              2:1 이상 = 유리 ✅
              1~2:1    = 보통 ⚠
              1 미만   = 불리 ❌

vsMA20 표시:
  +5.2% ✅ = 20일 이평선 위 5.2% (추세 우호)
  -1.3% ⚡ = 20일 이평선 아래 1.3% (눌림목)
  -8.0% ❌ = 이평선 크게 하락 (추세 약화)''')

    lines.append(sep2)

    # ── 4. 투자 전략 ──────────────────────────────────────────────────
    lines.append('''
━━ 4. 실전 투자 전략 (데이터 검증 기반) ━━━━━━━━━━━━━━━━━━━━━━

▶ 전략 1: 세력+스테이지 복합 필터 (최우선)
  조건: 세력점수 ≥ 70 AND 스테이지 🔥D-1 또는 ⚡D-2
  액션: 당일 또는 다음 시초가 매수
  근거: 세력이 활성화된 상태에서 ML이 급등 임박을 감지
  기대: D+1~D+3 내 5~15% 상승 목표

▶ 전략 2: 엘리트픽 Tier1/2 즉시 진입
  조건: 세력 ≥ 90 + 급등 ≥ 60 (Tier1)
         세력 ≥ 80 + 거래량 ≥ 2x (Tier2)
  액션: 당일 시초가 or 오더블록 눌림목 매수
  근거: 백테스트 예상적중 35% (시장 평균 2.1배)
  기대: 2~4일 내 급등. 손절은 -5% 기계적 실행

▶ 전략 3: 재발화 이력 추적 (중기 전략)
  조건: 이력 3회+ 재발화 종목 (★★ 표시)
  액션: OB 눌림목 구간에서 분할 매수 (3회 나눔)
  근거: 같은 종목이 반복 급등하는 패턴 = 세력 단골 종목
  기대: 1~3주 내 10~30% 상승

▶ 전략 4: 잠복형 → 폭발 전환 감지
  조건: 거래량 0.3x 미만 → 갑자기 1.5x+ 전환
  액션: 전환 당일 장중 확인 후 진입
  근거: 세력 매집 완료 후 진입 신호
  기대: 당일 5%+ 또는 다음날 갭상승''')

    lines.append(sep2)

    # ── 5. 리스크 관리 ────────────────────────────────────────────────
    lines.append('''
━━ 5. 리스크 관리 원칙 ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

■ 포지션 크기
  종목당 투자비중: 계좌의 3~5% 이하
  동시 보유 최대: 5~8종목 (분산)
  세력점수 90+: 최대 7%까지 허용

■ 손절 원칙 (반드시 기계적 실행)
  기본 손절: OB 하단 이탈 즉시 (-3~5%)
  최대 손절: -7% (어떤 이유로도 이 이상 보유 금지)
  손절 후: 동일 종목 재진입 최소 3일 대기

■ 이익 실현
  1차 목표(+8~10%): 50% 매도 + 손절가를 진입가로 이동
  2차 목표(+15~20%): 나머지 50% 매도
  트레일링 스톱: 고점 대비 -5% 하락 시 잔여 전량 정리

■ 매크로 리스크 조정
  매크로 점수 -10pt 이하: 전체 포지션 50% 축소
  VIX 30 이상: 신규 진입 중단, 보유 종목 방어 우선
  원달러 1,450원↑: 수출주 우선, 내수주 비중 축소''')

    lines.append(sep2)

    # ── 6. 체크리스트 ─────────────────────────────────────────────────
    lines.append('''
━━ 6. 매일 사용 체크리스트 ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

□ 매크로 점수 확인 (음수 크면 리스크 관리 모드)
□ 엘리트픽 확인 → 즉시 OB 전략 적용 대상 선정
□ 🔥D-1 + 세력≥70 종목 → 내일 시초가 매수 주문 준비
□ ⚡D-2 + 세력≥60 종목 → 워치리스트 추가, 내일 재확인
□ 🚀D+0 종목 → 기존 보유 시 1차 매도 검토
□ 📉D+1 종목 → 후속 상승 vs 되돌림 판단
□ 손절 주문 미리 걸기 (OB 하단 지정가)
□ 수익 중인 종목 트레일링 스톱 이동''')

    lines.append(sep2)

    # ── 7. 자동화 일정 ────────────────────────────────────────────────
    lines.append('''
━━ 7. 시스템 자동화 일정 ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

  평일 20:00  국내 학습 (daily_learner.py) — 전날 결과 반영
  평일 20:10  국내 스캔 + 이메일 발송 (본 리포트)
  매일 07:00  미국 스캔 + 이메일 발송 (US 리포트)
  매주 월요일 19:00  스테이지 모델 재학습 (한국+미국)

  ※ 모든 결과는 장 마감 후 데이터 기준
  ※ 당일 매수는 다음 거래일 시초가 기준으로 계획''')

    lines.append('')
    lines.append(sep)
    lines.append('  ※ 본 분석은 참고용입니다. 투자 판단과 책임은 본인에게 있습니다.')
    lines.append('  ※ 세력 분석 시스템 v2.0 | github.com/PhilipSon0414/stock_system_good')
    lines.append(sep)

    return '\n'.join(lines)


def main():
    guide = build_guide()
    subject = f'[세력분석 가이드] {datetime.now().strftime("%Y-%m-%d")} 리포트 읽는 법 + 투자 전략'
    result = send_report(subject=subject, body=guide)
    if result:
        print('  가이드 이메일 발송 완료')
    else:
        print('  이메일 발송 실패 또는 비활성화')
        print('\n--- 가이드 내용 미리보기 ---')
        print(guide[:2000])


if __name__ == '__main__':
    main()
